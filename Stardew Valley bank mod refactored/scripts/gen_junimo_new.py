for base in ["znm", "znm1", "znm2"]:
    for suffix in ["", "f", "h", "z"]:
        img = Image.new("RGBA", (SIZE, SIZE), (0,0,0,0))
        px = img.load()
        c = PAL[base]
        if suffix == "h":
            draw_side(px, c)
        elif suffix == "z":
            draw_back(px, c)
        elif suffix == "f":
            draw_front(px, c, arms_raised=True)
        else:
            draw_front(px, c)
        name = f"{base}{suffix}.png"
        path = os.path.join(OUT, name)
        img.save(path)
        print(f"Generated {name} to znm_new/")
